def scenario_flow():
    f = Flow(1400, 1000)
    f.title("Сценарий сопровождения ИС «Библиотека»: этапы")
    stages = [
        ("I", "Приёмка ИС на сопровождение: обследование,\nаудит, приём документации",
         LBLUE, BLUE),
        ("II", "Планирование и организация службы сопровождения\n(SLA, регламент, состав "
         "группы)", LBLUE, BLUE),
        ("III", "Ввод в эксплуатацию, настройка АРМ,\nобучение пользователей", LBLUE, BLUE),
        ("IV", "Текущее функционирование: консультации,\nмониторинг, регистрация инцидентов",
         GREEN, GREENL),
        ("V", "Плановое обслуживание: обновления, резервное\nкопирование, профилактика",
         GREEN, GREENL),
        ("VI", "Развитие ИС: доработки по заявкам,\nподключение новых модулей",
         GREEN, GREENL),
        ("VII", "Оценка качества: KPI, опрос пользователей,\nвнутренний аудит", ORANGE, ORANGEL),
        ("VIII", "Модернизация или замена ИС\n(при необходимости)", ORANGE, ORANGEL),
        ("IX", "Снятие с сопровождения: передача дел,\nархив, закрытие договора",
         ORANGE, ORANGEL),
    ]
    y = 78
    prev = None
    for i, (num, text, fill, line) in enumerate(stages):
        key = f"s{i}"
        f.block(key, 470, y, 460, 76, f"Этап {num}. " + text, "rect", fill, line, 13)
        if prev:
            f.link(prev, key)
        prev = key
        y += 96
    # результаты этапов слева
    results = ["Акт приёмки ИС,\nплан сопровождения", "Соглашение SLA,\nрегламент работ",
               "Обученный персонал,\nнастроенные АРМ", "Журнал обращений,\nотчёт по инцидентам",
               "План обновлений,\nрезервные копии", "Перечень доработок,\nновая версия ИС",
               "Отчёт SLA и KPI", "Решение о развитии\nИС", "Акт снятия\nс сопровождения"]
    for i, (res, (num, text, fill, line)) in enumerate(zip(results, stages)):
        yy = 78 + i * 96 + 24
        f.caption(1010, yy, res, 11, "#5D5D5D")
    f.legend(60, 130, [("#DCE9F7", "Подготовительные этапы"), ("#E7F4E8",
                       "Основные этапы эксплуатации"), ("#FDF0E2", "Завершающие этапы")],
             box=14)
    f.caption(60, 240, "Обратная связь", 12, "#5D5D5D", True)
    for i, t in enumerate(["заявки пользователей и результаты", "оценки качества уточняют",
                           "план сопровождения (этапы II–VI):", "состав работ, сроки "
                           "реакции,", "перечень обновлений и доработок"]):
        f.caption(60, 262 + i * 20, t, 11, "#5D5D5D")
    f.d.line([440, 240, 440, 780], fill="#AAAAAA", width=2)
    f._head((440, 240), (440, 340), "#AAAAAA", 2)
    f.save(os.path.join(OUT, "scenario_flow.png"))


